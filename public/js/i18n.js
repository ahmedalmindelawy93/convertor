let currentLang = 'en';

function t(key) {
  const catalog = I18N[currentLang] || I18N.en;
  return catalog[key] ?? I18N.en[key] ?? key;
}

function countForm(n, lang, kind) {
  const forms = {
    en: {
      page: ['page', 'pages'],
      file: ['file', 'files'],
    },
    ar: {
      page: ['صفحة', 'صفحتان', 'صفحات', 'صفحة'],
      file: ['ملف', 'ملفان', 'ملفات', 'ملف'],
    },
  };
  const set = forms[lang][kind];
  if (lang === 'en') return n === 1 ? set[0] : set[1];
  if (n === 1) return set[0];
  if (n === 2) return set[1];
  if (n >= 3 && n <= 10) return set[2];
  return set[3];
}

function localize(message) {
  if (!message || currentLang === 'en') return message;
  const exact = I18N.ar.err[message];
  if (exact) return exact;
  const rules = [
    [/^Unsupported format: (.+)$/, (_, ext) => `صيغة غير مدعومة: ${ext}`],
    [/^Unsupported format “(.+)”$/, (_, ext) => `صيغة غير مدعومة: ${ext}`],
    [/^Page (\d+) is outside 1–(\d+)$/, (_, page, count) => `الصفحة ${page} خارج النطاق 1–${count}`],
    [/^Could not read font \((.+)\)$/, (_, detail) => `تعذرت قراءة الخط (${detail})`],
    [/^Could not read JPEG 2000 file \((.+)\)$/, (_, detail) => `تعذرت قراءة ملف JPEG 2000 (${detail})`],
    [/^JPEG 2000 with (\d+) color components is not supported$/, (_, n) => `JPEG 2000 ذو ${n} مكوّنات لونية غير مدعوم`],
    [/the (\d+)-page limit was reached/g, (_, n) => `تم بلوغ حد ${n} صفحة`],
    [/imported (\d+) of (\d+) pages/g, (_, a, b) => `تم استيراد ${a} من ${b} صفحة`],
  ];
  let text = message;
  for (const [pattern, replacer] of rules) {
    if (pattern.global) text = text.replace(pattern, replacer);
    else if (pattern.test(text)) return text.replace(pattern, replacer);
  }
  return text;
}

function applyI18n(lang) {
  currentLang = lang === 'ar' ? 'ar' : 'en';
  const root = document.documentElement;
  root.lang = currentLang;
  root.dir = currentLang === 'ar' ? 'rtl' : 'ltr';
  document.title = t('title');
  document.body.dataset.drop = t('drop');
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((node) => {
    node.setAttribute('aria-label', t(node.dataset.i18nAria));
  });
  document.querySelectorAll('[data-lang]').forEach((node) => {
    node.classList.toggle('active', node.dataset.lang === currentLang);
    node.setAttribute('aria-pressed', node.dataset.lang === currentLang ? 'true' : 'false');
  });
  const pages = document.getElementById('export-pages');
  if (pages && ['all', 'الكل', ''].includes(pages.value.trim())) pages.value = t('all');
}
